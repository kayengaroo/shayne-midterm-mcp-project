/**
 * Runs the multi-step demo task across TWO MCP sessions and writes docs/demo-transcript.md.
 * Local mode (default): starts its own server in a temp dir.
 * Remote mode: DEMO_URL=https://<domain>/mcp DEMO_TOKEN=<token> npm run demo
 * NOTE: this is a scripted client (official SDK), not an LLM agent. See docs/testing.md.
 */
import fs from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { Client } from "@modelcontextprotocol/sdk/client/index.js";
import { StreamableHTTPClientTransport } from "@modelcontextprotocol/sdk/client/streamableHttp.js";
import { loadConfig } from "../src/config.js";
import { startServer, type RunningServer } from "../src/server.js";

const out: string[] = [];
let callCount = 0;
let errorCount = 0;

const clip = (s: string, n: number) => (s.length > n ? s.slice(0, n) + `… (${s.length} chars total)` : s);

async function connect(url: string, token: string) {
  const transport = new StreamableHTTPClientTransport(new URL(url), { requestInit: { headers: { Authorization: `Bearer ${token}` } } });
  const client = new Client({ name: "demo-agent", version: "1.0.0" });
  await client.connect(transport);
  return { client, sessionId: transport.sessionId ?? "?" };
}

async function step(client: Client, name: string, args: Record<string, unknown>, why: string) {
  callCount++;
  const res = await client.callTool({ name, arguments: args });
  const text = (res.content as Array<{ text: string }>)[0]?.text ?? "";
  if (res.isError) errorCount++;
  out.push(`**${callCount}. \`${name}\`** — ${why}`, "```json", clip(JSON.stringify(args), 500), "```", `Result${res.isError ? " (**isError**, expected in this step)" : ""}:`, "```", clip(text, 700), "```", "");
  try { return JSON.parse(text); } catch { return { error: text }; }
}

async function main() {
  let server: RunningServer | undefined;
  let url = process.env.DEMO_URL ?? "";
  let token = process.env.DEMO_TOKEN ?? "";
  let tmp = "";
  if (!url) {
    tmp = await fs.mkdtemp(path.join(os.tmpdir(), "demo-"));
    token = "demo-token-1234567890abcdef";
    server = await startServer(loadConfig({ MCP_AUTH_TOKEN: token, PORT: "0", WORKSPACE_ROOT: path.join(tmp, "workspace"), LOG_DIR: path.join(tmp, "logs") }));
    url = `http://127.0.0.1:${server.port}/mcp`;
  }
  const mode = process.env.DEMO_URL ? "remote (HTTPS tunnel URL)" : "local in-process server";

  out.push("# Demo transcript: multi-step task across two MCP sessions", "",
    `Generated by \`npm run demo\` (scripts/demo.ts) on ${new Date().toISOString()}. Mode: **${mode}**.`,
    "The client is a scripted program using the official MCP SDK over Streamable HTTP with bearer-token auth, **not an LLM agent**. " +
    "Session 2 is a new MCP session and has no memory of session 1: it recovers context only from the handoff files.", "",
    "**Task:** build a small todo list, tick one item, clean up a scratch file, and checkpoint, split across two agents/sessions.", "");

  // ---------------- Session 1 ----------------
  const s1 = await connect(url, token);
  out.push(`## Session 1: agent \`planner\` (Mcp-Session-Id \`${s1.sessionId}\`)`, "");
  const state = (await step(s1.client, "handoff_read", { file: "PROJECT_STATE" }, "always start by reading the handoff state")).files[0];
  await step(s1.client, "write_file", { path: "notes/todo.md", content: "- [ ] write intro\n- [ ] write summary\n- [ ] remove scratch\n" }, "create the todo list");
  await step(s1.client, "write_file", { path: "notes/scratch.txt", content: "temporary notes\n" }, "create a scratch file to clean up later");
  await step(s1.client, "read_file", { path: "../../etc/passwd" }, "security check: path traversal must be rejected");
  await step(s1.client, "handoff_update", { file: "PLAN_LOG", mode: "append", agent: "planner", content: "Created notes/todo.md (3 items) and notes/scratch.txt." }, "log what was done");
  await step(s1.client, "handoff_update", { file: "PROJECT_STATE", mode: "replace", agent: "planner", if_version: state.version,
    content: "# PROJECT_STATE\n\n## Goal\nBuild and finish notes/todo.md.\n\n## Status\nSession 1 done: todo.md created (0/3 ticked). scratch.txt exists.\n\n## Remaining\n- tick 'write intro'\n- delete notes/scratch.txt\n- checkpoint\n\n## Next action\nsearch todo.md for '[ ]', tick first item, delete scratch.txt, git_commit.\n" }, "write the snapshot the next agent will read");
  await step(s1.client, "git_commit", { message: "session 1: create todo list" }, "commit so the work is recoverable");
  await s1.client.close();
  out.push("_Session 1 closed. The next session is a different agent with an empty context._", "");

  // ---------------- Session 2 ----------------
  const s2 = await connect(url, token);
  out.push(`## Session 2: agent \`implementer\` (Mcp-Session-Id \`${s2.sessionId}\`)`, "");
  const ctx = await step(s2.client, "handoff_read", {}, "recover context from the handoff files only");
  const st2 = ctx.files.find((f: any) => f.file === "PROJECT_STATE");
  await step(s2.client, "search_files", { query: "[ ]", path: "notes" }, "find open items without reading every file");
  await step(s2.client, "str_replace", { path: "notes/todo.md", old_str: "- [ ] write intro", new_str: "- [x] write intro" }, "tick the first item");
  await step(s2.client, "delete_file", { path: "notes/scratch.txt", confirm: false }, "destructive-action gate: refused without confirm=true");
  await step(s2.client, "delete_file", { path: "notes/scratch.txt", confirm: true }, "confirmed delete (moved to .trash, recoverable)");
  await step(s2.client, "git_diff", { path: "notes/todo.md" }, "review the change before committing");
  await step(s2.client, "git_commit", { message: "session 2: tick intro, remove scratch" }, "commit");
  await step(s2.client, "handoff_update", { file: "CHECKPOINTS", mode: "append", agent: "implementer", content: "1/3 todo items ticked; scratch.txt removed (in .trash); committed." }, "record a checkpoint");
  await step(s2.client, "handoff_update", { file: "DECISIONS", mode: "append", agent: "implementer", content: "Delete uses soft-delete to .trash/ so mistakes are recoverable." }, "record a decision");
  await step(s2.client, "handoff_update", { file: "PROJECT_STATE", mode: "replace", agent: "implementer", if_version: st2.version,
    content: "# PROJECT_STATE\n\n## Status\nSession 2 done: 1/3 ticked, scratch removed, committed.\n\n## Remaining\n- tick 'write summary'\n\n## Next action\nContinue with the remaining todo items.\n" }, "update the snapshot (if_version prevents overwriting someone else's update)");
  await step(s2.client, "git_log", { max_count: 5 }, "verify history");

  // evidence: final handoff files
  const finalState = await s2.client.callTool({ name: "handoff_read", arguments: { tail_lines: 2000 } });
  const files = JSON.parse((finalState.content as Array<{ text: string }>)[0]!.text).files as Array<{ file: string; content: string }>;
  await fs.mkdir("docs/demo", { recursive: true });
  for (const f of files) await fs.writeFile(`docs/demo/${f.file}.md`, f.content + "\n");
  await s2.client.close();

  out.push("## Summary", "", `- Sessions: 2 (different \`Mcp-Session-Id\`s)`, `- Tool calls: ${callCount} (${errorCount} intentional errors: path traversal and missing confirm)`,
    "- Final handoff files are saved in `docs/demo/`.", "");
  await fs.writeFile("docs/demo-transcript.md", out.join("\n"));
  if (server) {
    await fs.copyFile(server.logger.file, "docs/demo/calls.jsonl");
    await server.close();
    await fs.rm(tmp, { recursive: true, force: true });
  }
  console.log(`Wrote docs/demo-transcript.md (${callCount} calls, ${errorCount} intentional errors)`);
}
main().catch((e) => { console.error(e); process.exit(1); });
